import { chromium } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
const [, , route, auth = "ada"] = process.argv;
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, storageState: auth === "none" ? undefined : `e2e/.auth/${auth}.json` });
const p = await ctx.newPage(); await p.goto("http://localhost:5173" + route); await p.waitForTimeout(2500);
const r = await new AxeBuilder({ page: p }).withTags(["wcag2a", "wcag2aa"]).exclude("iframe").analyze();
for (const v of r.violations) for (const n of v.nodes.slice(0, 4)) console.log(v.id, v.impact, "|", n.target.join(" "), "|", (n.any[0]?.message || n.failureSummary || "").replace(/\n/g, " ").slice(0, 170), "|", n.html.slice(0, 110));
console.log("h1:", await p.locator("h1").allInnerTexts());
await b.close();
